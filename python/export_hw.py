"""Step 3: write the files the Verilog design and testbench load with $readmemh.

    python python/export_hw.py

For each bit width this creates weights/int<bits>/:
  weights.mem        all weights, BW bits each (hex, two's complement), one per line
                     W1 row-major (address = j*N_IN + i), then W2 from address W2_BASE
                     (address = W2_BASE + k*N_HID + j)
  biases.mem         b1 (N_HID values) then b2 (from address B2_BASE), ACC_W bits each
  test_inputs.mem    N_TEST input vectors, N_IN values each, BW bits
  test_expected.mem  class the integer model predicts for each vector (8-bit)
  test_labels.mem    true word for each vector (8-bit)
  test_hidden.mem    expected hidden activations h (N_HID per vector, BW bits) - for debugging
  test_logits.mem    expected layer-2 outputs (N_OUT per vector, ACC_W bits) - for debugging
  kws_params.vh      `define constants (bit width, sizes, SHIFT, ...)
  summary.txt        human-readable description and accuracy
"""
import argparse
import sys

import numpy as np

import config as C
import quant as Q


def to_hex(value, width):
    return format(int(value) & ((1 << width) - 1), f"0{(width + 3) // 4}x")


def write_mem(path, values, width):
    path.write_text("\n".join(to_hex(v, width) for v in np.ravel(values)) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--features", default=str(C.FEATURES_FILE))
    ap.add_argument("--n-test", type=int, default=C.N_HW_TEST_VECTORS)
    args = ap.parse_args()

    d = np.load(args.features)
    X_test, y_test = d["X_test"], d["y_test"]
    rng = np.random.default_rng(C.SEED)
    pick = np.sort(rng.choice(len(y_test), min(args.n_test, len(y_test)), replace=False))

    for bits in C.BIT_WIDTHS:
        m, words = Q.load_int_model(C.RESULTS_DIR / f"qmodel_int{bits}.npz")
        out = C.HW_DIR / f"int{bits}"
        out.mkdir(parents=True, exist_ok=True)
        n_hid, n_in = m["W1"].shape
        n_out = m["W2"].shape[0]
        bw, acc_w = bits, m["acc_w"]

        x = Q.quantize(X_test[pick], m["s_x"], bits)
        pred, hidden, logits = Q.int_forward(m, x)
        full_acc = Q.accuracy(m, X_test, y_test)
        vec_acc = float(np.mean(pred == y_test[pick]))

        write_mem(out / "weights.mem", np.concatenate([m["W1"].ravel(), m["W2"].ravel()]), bw)
        write_mem(out / "biases.mem", np.concatenate([m["b1"], m["b2"]]), acc_w)
        write_mem(out / "test_inputs.mem", x, bw)
        write_mem(out / "test_expected.mem", pred, 8)
        write_mem(out / "test_labels.mem", y_test[pick], 8)
        write_mem(out / "test_hidden.mem", hidden, bw)
        write_mem(out / "test_logits.mem", logits, acc_w)

        classes = " ".join(f"{i}={w}" for i, w in enumerate(words))
        defines = [
            ("BW", bw, "weight / activation bit width"),
            ("ACC_W", acc_w, "accumulator width (no overflow possible)"),
            ("N_IN", n_in, "inputs (MFCC features)"),
            ("N_HID", n_hid, "hidden neurons"),
            ("N_OUT", n_out, "output classes (words)"),
            ("CLASS_W", max(1, int(np.ceil(np.log2(n_out)))), "bits for a class index"),
            ("SHIFT", m["shift"], "hidden-layer requantization right shift"),
            ("QMAX", Q.qmax(bits), "largest activation / weight value"),
            ("N_WEIGHTS", n_in * n_hid + n_hid * n_out, "lines in weights.mem"),
            ("W2_BASE", n_in * n_hid, "address of first layer-2 weight"),
            ("N_BIASES", n_hid + n_out, "lines in biases.mem"),
            ("B2_BASE", n_hid, "address of first layer-2 bias"),
            ("N_TEST", len(pick), "test vectors in test_inputs.mem"),
        ]
        vh = [f"// Auto-generated by python/export_hw.py - INT{bits} keyword spotting model",
              f"// Classes: {classes}"]
        vh += [f"`define KWS_{name:10s}{value:<8d}// {note}" for name, value, note in defines]
        (out / "kws_params.vh").write_text("\n".join(vh) + "\n")

        summary = f"""INT{bits} keyword spotting model
Classes: {classes}
Network: {n_in} -> {n_hid} (ReLU) -> {n_out} -> argmax
BW = {bw}, ACC_W = {acc_w}, SHIFT = {m['shift']}, QMAX = {Q.qmax(bits)}
Input scale s_x = {m['s_x']:.6f}  (x_int = clamp(round(normalized_feature / s_x), -QMAX, QMAX))
Weight scales: s_w1 = {m['s_w1']:.6f}, s_w2 = {m['s_w2']:.6f}
Weight memory: {n_in * n_hid + n_hid * n_out} x {bw} bits = {(n_in * n_hid + n_hid * n_out) * bw // 8} bytes
Integer-model accuracy on the full test set: {100 * full_acc:.2f}% ({len(y_test)} clips)
Integer-model accuracy on the {len(pick)} exported test vectors: {100 * vec_acc:.2f}%
The Verilog output must equal test_expected.mem for every vector (bit-exact match).
"""
        (out / "summary.txt").write_text(summary)
        print(summary)
        print(f"Wrote {out}\n")


if __name__ == "__main__":
    sys.exit(main())
